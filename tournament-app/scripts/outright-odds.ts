// Works out the outright wager table (web/src/lib/outrightTable.ts) by
// playing many tournaments through the real engine.
//
//   bun run scripts/outright-odds.ts [--runs 20000] [--spread 1.0]
//
// Each simulated player has a hidden skill ~ Normal(0, spread); the better
// player wins a match with chance 1 / (1 + e^-(skill gap)). At spread 1.0 the
// best of 12 beats a middling player about 80% of the time. (With coin-flip
// matches seeding is worth nothing, so skill is what makes a good finish
// mean something.) For each player count 8–15 it counts how often each
// overall standing (lib/outrights.ts) wins the tournament and each path.
//
// scripts/calibrate.ts measures the spread from a past event's results.
// Takes about 10 minutes at 20,000 runs.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  STRUCTURES,
  applyResult,
  champion,
  computeStandings,
  createGroupStage,
  generateKnockout,
  makeRng,
  resolve,
  type State,
} from "../engine/src/index.ts";
import { OUTRIGHT_MARKETS, PATHS, overallStanding, pathWinner, type OutrightMarket } from "../web/src/lib/outrights.ts";

const arg = (name: string, fallback: number) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? Number(process.argv[i + 1]) : fallback;
};
const RUNS = arg("runs", 20000);
const SPREAD = arg("spread", 1.0);
const rng = makeRng(20270301);

function normal(): number {
  const u = Math.max(rng(), 1e-12); // Box–Muller
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rng());
}

const table: Record<number, Record<OutrightMarket, number[]>> = {};
for (let n = 8; n <= 15; n++) {
  const st = STRUCTURES[n];
  const wins: Record<OutrightMarket, number[]> = { champion: [], gilded: [], iron: [], ashen: [] };
  for (const k of OUTRIGHT_MARKETS) wins[k] = Array(n).fill(0);

  for (let r = 0; r < RUNS; r++) {
    const skill = new Map<string, number>();
    const players = Array.from({ length: n }, (_, i) => ({ id: `p${i}`, name: `P${i}` }));
    for (const p of players) skill.set(p.id, normal() * SPREAD);
    const stage = createGroupStage(players, rng);
    const state: State = { structure: stage.structure, players: stage.players, matches: stage.matches };
    const play = (code: string) => {
      const m = state.matches.find((x) => x.code === code)!;
      const gap = skill.get(m.p1!)! - skill.get(m.p2!)!;
      const loser = Math.floor(rng() * 5);
      if (rng() < 1 / (1 + Math.exp(-gap))) applyResult(state, code, 5, loser);
      else applyResult(state, code, loser, 5);
    };

    for (const gm of state.matches.filter((m) => m.stage === "group")) play(gm.code);
    resolve(state);

    // Standings when outrights open (the Respite).
    const rows = st.groups.flatMap((_, g) => {
      const ids = state.players.filter((p) => p.group === g).map((p) => p.id);
      return computeStandings(ids, state.matches.filter((m) => m.stage === "group" && m.group === g)).map((row) => ({
        ...row,
        group: g,
        place: state.players.find((p) => p.id === row.playerId)!.finalGroupRank!,
      }));
    });
    const standing = overallStanding(st, rows);

    generateKnockout(state, rng);
    for (let g = 0; g < 300; g++) {
      const next = state.matches.find((m) => m.stage !== "group" && m.status === "ready");
      if (!next) break;
      play(next.code);
    }

    const rrTop = (stage: string) => {
      const rr = state.matches.filter((m) => m.stage === stage);
      const ids = [...new Set(rr.flatMap((m) => [m.p1!, m.p2!]))];
      return computeStandings(ids, rr)[0]?.playerId ?? null;
    };
    const credit = (k: OutrightMarket, id: string | null | undefined) => {
      const i = id ? standing.indexOf(id) : -1;
      if (i >= 0) wins[k][i]++;
    };
    credit("champion", champion(state));
    for (const p of PATHS) credit(p, pathWinner(st, p, state.matches, rrTop));
  }

  table[n] = { champion: [], gilded: [], iron: [], ashen: [] };
  for (const k of OUTRIGHT_MARKETS) table[n][k] = wins[k].map((w) => Math.round((w / RUNS) * 10000) / 10000);
  console.log(`${n} players done`);
}

const out = `// GENERATED by scripts/outright-odds.ts — don't edit by hand; run it again.
//   ${new Date().toISOString().slice(0, 10)}: ${RUNS} runs per player count, skill spread ${SPREAD}
// For each player count, each market's chance of winning by overall
// standing (index 0 = #1). 0: can't win it from there. Odds are made from
// these in lib/outrightMarket.ts (house edge and cap), so changing those needs no
// new run.

import type { OutrightMarket } from "./outrights";

export const OUTRIGHT_SPREAD = ${SPREAD};

export const OUTRIGHT_CHANCES: Record<number, Record<OutrightMarket, number[]>> = {
${Object.entries(table)
  .map(
    ([n, markets]) =>
      `  ${n}: {\n${OUTRIGHT_MARKETS.map((k) => `    ${k}: [${markets[k].join(", ")}],`).join("\n")}\n  },`,
  )
  .join("\n")}
};
`;
const file = join(import.meta.dir, "../web/src/lib/outrightTable.ts");
writeFileSync(file, out);
console.log(`Wrote ${file}`);
